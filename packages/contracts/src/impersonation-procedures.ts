export type ImpersonationProcedurePath = keyof typeof IMPERSONATION_PROCEDURE_KIND;
export type ImpersonationProcedureKind =
  (typeof IMPERSONATION_PROCEDURE_KIND)[ImpersonationProcedurePath];

/** Ops procedures that remain callable while impersonating. */
export const IMPERSONATION_ALLOWED_OPS = [
  "ops.stopImpersonation",
  "ops.switchImpersonation",
] as const;

export function impersonationProcedureKind(
  path: string,
): ImpersonationProcedureKind | undefined {
  return (IMPERSONATION_PROCEDURE_KIND as Record<string, ImpersonationProcedureKind>)[path];
}

export function isImpersonationReadProcedure(path: string): boolean {
  return impersonationProcedureKind(path) === "read";
}

/** Deny-by-default allow check used by the API guard. */
export function isImpersonationAllowedProcedurePath(path: string): boolean {
  const kind = impersonationProcedureKind(path);
  if (kind === "read") return true;
  return (IMPERSONATION_ALLOWED_OPS as readonly string[]).includes(path);
}
